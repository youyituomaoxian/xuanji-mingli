console.log('=== 农历闰月/边界权威历书验收（' + CASES.length + ' 例） ===');
for (const c of CASES) {
  const r = A.solarToLunar(c[0], c[1], c[2]);
  const got = r ? (r.year + '/' + r.month + '/' + r.day + (r.leap ? '闰' : '')) : 'null';
  const want = c[3] + '/' + c[4] + '/' + c[5] + (c[6] ? '闰' : '');
  const ok = got === want;
  if (ok) pass++; else fail++;
  console.log((ok ? '  PASS ' : '  FAIL ') + c[7] + ' → 得到 ' + got + '，期望 ' + want);
}
console.log('\n权威历书验收 pass=' + pass + ' fail=' + fail);
process.exit(fail ? 1 : 0);
